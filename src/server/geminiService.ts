import { GoogleGenAI } from "@google/genai";

export async function handleGeminiResearch(
  prompt: string,
  history: Array<{ role: 'user' | 'model'; parts: Array<{ text: string }> }> = []
) {
  const apiKey = process.env.GEMINI_API_KEY;

  if (!apiKey || apiKey === 'MY_GEMINI_API_KEY') {
    return {
      success: false,
      error: "GEMINI_API_KEY_NOT_CONFIGURED",
      message:
        "The Gemini API key is not currently configured on the server. To enable real-time scholarly research with Gemini, please add your GEMINI_API_KEY to the .env file in the project root directory (e.g. GEMINI_API_KEY=\"your_key_here\") and restart the server.",
    };
  }

  if (!prompt || typeof prompt !== 'string' || !prompt.trim()) {
    return {
      success: false,
      error: "EMPTY_PROMPT",
      message: "Please enter a valid architectural or historical heritage research inquiry.",
    };
  }

  try {
    const ai = new GoogleGenAI({
      apiKey,
      httpOptions: {
        headers: {
          'User-Agent': 'sanskriti-heritage-archive/1.0',
        },
      },
    });

    const systemInstruction = `You are the lead Heritage Research Scholar and Archaeological Historian for 'SANSKRITI — India's Living Digital Heritage Archive'.
Your task is to provide authoritative, rigorous, historically grounded, and evocative architectural and cultural analysis of India's heritage monuments, sacred geography, dynasties, conservation science, and living traditions.
Tone: Academic yet accessible, respectful, richly descriptive, precise about dynasties, centuries, materials (e.g., khondalite, Makrana marble, basalt, sandstone), and architectural styles (Maru-Gurjara, Kalinga, Dravidian, Nagara, Indo-Islamic).
Format: Use clear headings, bullet points for structural analysis where relevant, and historical citations where appropriate. If asked about one of the six core monuments (Rani ki Vav, Taj Mahal, Hampi, Konark Sun Temple, Ajanta Caves, Modhera Sun Temple), offer deep insight into their engineering, iconography, and historical context.`;

    // Multiturn contents sanitization:
    // Gemini API requires alternating user -> model -> user turns starting with a user turn.
    const contents: Array<{ role: 'user' | 'model'; parts: Array<{ text: string }> }> = [];

    if (Array.isArray(history)) {
      for (const msg of history) {
        if (!msg || !Array.isArray(msg.parts) || !msg.parts[0]?.text?.trim()) continue;
        const role = msg.role === 'model' ? 'model' : 'user';
        const text = msg.parts[0].text.trim();
        const lastMsg = contents[contents.length - 1];

        if (!lastMsg) {
          // Gemini multi-turn must start with user
          if (role === 'user') {
            contents.push({ role: 'user', parts: [{ text }] });
          }
        } else if (lastMsg.role === role) {
          // Merge consecutive turns of the same role
          lastMsg.parts[0].text += `\n\n${text}`;
        } else {
          contents.push({ role, parts: [{ text }] });
        }
      }
    }

    // Append the user's current query
    const lastEntry = contents[contents.length - 1];
    if (lastEntry && lastEntry.role === 'user') {
      lastEntry.parts[0].text += `\n\n${prompt.trim()}`;
    } else {
      contents.push({
        role: 'user',
        parts: [{ text: prompt.trim() }],
      });
    }

    // Try available models (with prioritized fallback)
    const modelCandidates = [
      process.env.GEMINI_MODEL,
      "gemini-2.5-flash",
      "gemini-2.0-flash",
      "gemini-1.5-flash",
    ].filter(Boolean) as string[];

    let lastError: any = null;
    let responseText: string | null = null;

    for (const model of modelCandidates) {
      try {
        const response = await ai.models.generateContent({
          model,
          contents,
          config: {
            systemInstruction,
          },
        });
        if (response && response.text) {
          responseText = response.text;
          break;
        }
      } catch (err: any) {
        lastError = err;
        console.warn(`Gemini generation failed with model ${model}:`, err.message);
        // Continue to fallback model if model not found or quota issues
      }
    }

    if (responseText) {
      return {
        success: true,
        text: responseText,
      };
    }

    throw lastError || new Error("No response generated by the Gemini research engine.");
  } catch (err: any) {
    console.error("Gemini research service error:", err);
    return {
      success: false,
      error: "GEMINI_EXECUTION_ERROR",
      message: err.message || "Failed to generate research response from Gemini API.",
    };
  }
}
